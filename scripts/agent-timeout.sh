#!/usr/bin/env bash
# レビュー用エージェントの**放置を防ぐ目覚まし**(issue #83)。
#
#   Bash(run_in_background: true) で起動する:
#     scripts/agent-timeout.sh 10 aXXXX aYYYY
#
# 指定分だけ待って1回だけ出力し、終了する。`run_in_background` のコマンドは
# **終了時に必ず通知が来る**ので、それが「まだ動いているなら止めろ」という割り込みになる。
#
# なぜ要るか: 1セッションで**4回**、レビュー用エージェントが長時間ハングして手が止まった。
# 対策を3つ打った(範囲指定 / worktree+フルビルドを使わせない / 観点は3つまで)が4回目も
# 起きている。共通していたのは「**気づけない**」こと——`TaskList` にエージェントは出ず、
# 経過時間も見えないので、待っている側からは「まだ考えている」と区別がつかない。
# 人間に指摘されて初めて気づく、という状態だった。
#
# **判定はしない**。止めるかどうかは通知を受けてから決める(終わっていれば無視してよい)。
# エージェントが先に終わったら、この目覚ましは TaskStop で止めてよい——放っておいても
# 1回鳴るだけなので、消し忘れの害は小さい。
set -u

mins=${1:?"使い方: agent-timeout.sh <分> [エージェントID...]"}
shift || true

sleep $((mins * 60))

echo "=== TIMEOUT: レビュー用エージェントが ${mins} 分経過"
if [ "$#" -gt 0 ]; then
	echo "まだ動いているものがあれば TaskStop で止める(IDは起動時に控えたもの):"
	for id in "$@"; do echo "  TaskStop: $id"; done
else
	echo "止めるには起動時のエージェントIDが要る(TaskList には出ない)"
fi
echo "1観点落ちても他が実機検証していれば網羅性は保てる。詳細は docs/handoff.md 手順6'"
